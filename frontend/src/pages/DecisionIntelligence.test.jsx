describe('DecisionIntelligence page: terminal snapshot', () => {
  it('skips SHAP and scenario for a terminal snapshot but still shows portfolio context', async () => {
    listProjectSnapshots.mockResolvedValue([{ reporting_month: '2023-06', is_terminal_snapshot: true }])
    getDecisionIntelligence.mockResolvedValue(
      baseResponse({
        project: baseProject({ reporting_month: '2023-06', is_terminal_snapshot: true, project_status: 'Completed' }),
        prediction_status: 'actual_outcome',
        predictions: {
          significant_delay: { task: 'significant_delay', model_used: null, predicted_class: null, probability_of_significant_delay: null, actual_value: 1 },
          final_delay_days: { task: 'final_delay_days', model_used: null, predicted_final_delay_days: null, actual_value: 132 },
          cost_overrun: { task: 'cost_overrun', model_used: null, predicted_class: null, probability_of_cost_overrun: null, actual_value: 0 },
          final_cost_overrun_pct: { task: 'final_cost_overrun_pct', model_used: null, predicted_final_cost_overrun_pct: null, actual_value: 4.2 },
        },
        risk_drivers: [],
        shap_skipped_reason: 'Skipped: this snapshot is terminal and already records the known final outcome.',
        scenario: null,
        scenario_skipped_reason: 'Skipped: this snapshot is terminal, so no live SHAP driver exists to anchor a scenario.',
        driver_alignment: driverAlignment().map((a) => ({ ...a, live_top_driver: null, live_top_driver_identity: null, agreement: null })),
      })
    )

    renderAt('HRI-0006')

    expect(await screen.findByText(/is terminal and already records the known final outcome/)).toBeInTheDocument()
    expect(screen.getByText(/no live SHAP driver exists to anchor a scenario/)).toBeInTheDocument()
    // Portfolio position still renders for a terminal request.
    expect(screen.getByText('Portfolio Position')).toBeInTheDocument()
  })
})

