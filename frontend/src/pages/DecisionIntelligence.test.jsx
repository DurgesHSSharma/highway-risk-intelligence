function renderAt(projectId) {
  render(
    <MemoryRouter initialEntries={[`/projects/${projectId}/decision-intelligence`]}>
      <Routes>
        <Route path="/projects/:projectId/decision-intelligence" element={<DecisionIntelligence />} />
        <Route path="/projects/:projectId/risk-summary" element={<div>risk-summary page</div>} />
        <Route path="/projects/:projectId/simulator" element={<div>simulator page</div>} />
      </Routes>
    </MemoryRouter>
  )
}

describe('DecisionIntelligence page: loading and success', () => {
  it('shows a loading state before resolving', async () => {
    listProjectSnapshots.mockResolvedValue([{ reporting_month: '2022-12', is_terminal_snapshot: false }])
    getDecisionIntelligence.mockImplementation(() => new Promise(() => {}))

    renderAt('HRI-0006')
    expect(await screen.findByText(/Computing decision intelligence/)).toBeInTheDocument()
  })

  it('renders executive risk, percentile, peer groups, and driver alignment on success', async () => {
    listProjectSnapshots.mockResolvedValue([{ reporting_month: '2022-12', is_terminal_snapshot: false }])
    getDecisionIntelligence.mockResolvedValue(baseResponse())

    renderAt('HRI-0006')

    expect(await screen.findByText(/Delhi-Dehradun Expressway/)).toBeInTheDocument()
    // Portfolio percentile (rendered both in the executive summary and the
    // dedicated Portfolio Position section)
    expect(screen.getAllByText(/88\.3th|88\.2th|88th/).length).toBeGreaterThan(0)
    expect(screen.getAllByText(/High/).length).toBeGreaterThan(0)
    // Peer group cards for all three dimensions
    expect(screen.getAllByText(/Uttarakhand/).length).toBeGreaterThan(0)
    expect(screen.getByText('State Peers')).toBeInTheDocument()
    expect(screen.getByText('Project-Type Peers')).toBeInTheDocument()
    expect(screen.getByText('Contractor Peers')).toBeInTheDocument()
    // Small-sample flag preserved, not dropped
    expect(screen.getByText('Small sample')).toBeInTheDocument()
  })
})

describe('DecisionIntelligence page: API error', () => {
  it('shows an error state with retry when the request fails', async () => {
    listProjectSnapshots.mockResolvedValue([{ reporting_month: '2022-12', is_terminal_snapshot: false }])
    getDecisionIntelligence.mockRejectedValue(new Error('network down'))

    renderAt('HRI-0006')
    expect(await screen.findByText(/Unable to load decision intelligence/)).toBeInTheDocument()
  })
})

describe('DecisionIntelligence page: cache unavailable / project not in cache', () => {
  it('shows an explicit cache_unavailable message instead of fabricating a percentile', async () => {
    listProjectSnapshots.mockResolvedValue([{ reporting_month: '2022-12', is_terminal_snapshot: false }])
    getDecisionIntelligence.mockResolvedValue(
      baseResponse({
        risk_positioning: riskPositioning({
          status: 'cache_unavailable',
          message: 'The portfolio prediction cache has not been generated yet.',
          composite_risk_score: null,
          risk_level: null,
          percentile: null,
          cohort_size: null,
        }),
      })
    )

    renderAt('HRI-0006')
    expect(await screen.findByText('Portfolio prediction cache unavailable.')).toBeInTheDocument()
    expect(screen.getByText(/has not been generated yet/)).toBeInTheDocument()
  })

  it('shows an explicit project_not_in_cache message', async () => {
    listProjectSnapshots.mockResolvedValue([{ reporting_month: '2022-12', is_terminal_snapshot: false }])
    getDecisionIntelligence.mockResolvedValue(
      baseResponse({
        risk_positioning: riskPositioning({
          status: 'project_not_in_cache',
          message: 'This project does not have a row in the current portfolio prediction cache.',
          composite_risk_score: null,
          risk_level: null,
          percentile: null,
          cohort_size: 400,
        }),
      })
    )

    renderAt('HRI-0006')
    expect(await screen.findByText('This project is not in the current portfolio prediction cache.')).toBeInTheDocument()
  })
})

